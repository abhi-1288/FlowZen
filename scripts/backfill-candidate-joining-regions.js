// One-off migration: give existing candidates a `joiningRegionLabel` where one
// can be derived without guessing. Idempotent. Run with:
//
//   node scripts/backfill-candidate-joining-regions.js [--dry-run]
//
// WHY THIS IS DELIBERATELY CONSERVATIVE
//
// `joiningRegionLabel` is the office that owns a hire. Getting it wrong is worse
// than leaving it empty: it decides which region's head approves the join, which
// office the employee is filed under on arrival, and which recruiters can see the
// candidate at all. So a region is only written when the record already states it
// unambiguously.
//
// Sources, in order:
//   1. an accepted offer's `regionLabel` (already canonical office labels);
//   2. any offer's `regionLabel`;
//   3. the job's `regionLabel`.
//
// Every value is matched against the company's own `addresses[].label` and
// skipped if it matches none. Notably NOT used:
//
//   - `ATSCandidate.regionLabel`. It is a detected STATE ("Maharashtra"), written
//     by `lib/candidate-region.ts`, and occasionally an office label from the
//     ats-score path. Copying it here is how the two label spaces got conflated
//     in the first place.
//   - the creating HR's region. The bulk transfer was built precisely so a
//     candidate's office no longer follows whoever happened to process them, so
//     re-deriving it that way would rebuild the bug this feature fixes.
//
// Anything left blank stays in the unassigned pool, which every recruiter can
// see. That is the correct resting state for a hire nobody has routed yet.

const fs = require("fs");
const path = require("path");
const mongoose = require("mongoose");

const DRY_RUN = process.argv.includes("--dry-run");

function loadEnvLocal() {
  const envPath = path.join(__dirname, "..", ".env.local");
  if (!fs.existsSync(envPath)) return;
  const content = fs.readFileSync(envPath, "utf8");
  for (const line of content.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    const value = trimmed.slice(eq + 1).trim();
    if (!(key in process.env)) process.env[key] = value;
  }
}

loadEnvLocal();

const uri =
  process.env.NODE_ENV === "production"
    ? process.env.ATLAS_URI
    : process.env.MONGODB_URI;

if (!uri) {
  console.error("No MONGODB_URI / ATLAS_URI found in the environment.");
  process.exit(1);
}

const UNSET_REGION = { $in: ["", null] };

async function main() {
  await mongoose.connect(uri);
  const db = mongoose.connection.db;

  const companies = await db
    .collection("companies")
    .find({}, { projection: { addresses: 1 } })
    .toArray();

  // Office labels per company, keyed case-insensitively and mapped to the label
  // as the company actually spells it.
  //
  // The mapped (configured) spelling is returned, not the incoming string. A
  // source row that says "noida region" must not be rewritten as "noida region":
  // downstream `regionEntryOf` and the transfer endpoint compare against the
  // configured label, so preserving the loose casing would leave the backfilled
  // value matching nothing and re-forking the region identity this script exists
  // to repair.
  const labelsByCompany = new Map();
  for (const company of companies) {
    const addresses = Array.isArray(company.addresses) ? company.addresses : [];
    const map = new Map();
    for (const address of addresses) {
      const label = String(address?.label ?? "").trim();
      if (label) map.set(label.toLowerCase(), label);
    }
    labelsByCompany.set(String(company._id), map);
  }

  const canonical = (companyId, value) => {
    const raw = String(value ?? "").trim();
    if (!raw) return "";
    const known = labelsByCompany.get(String(companyId));
    if (!known) return "";
    return known.get(raw.toLowerCase()) || "";
  };

  const jobs = await db
    .collection("atsjobs")
    .find(
      { regionLabel: { $nin: ["", null] } },
      { projection: { company: 1, regionLabel: 1 } },
    )
    .toArray();
  const jobRegion = new Map();
  for (const job of jobs) {
    const region = canonical(job.company, job.regionLabel);
    if (region) jobRegion.set(String(job._id), region);
  }

  const offers = await db
    .collection("atsoffers")
    .find(
      { regionLabel: { $nin: ["", null] } },
      { projection: { candidate: 1, company: 1, regionLabel: 1, status: 1 } },
    )
    .toArray();

  // An accepted offer is the strongest signal: it was generated by the region
  // that agreed to take the hire.
  const offerRegion = new Map();
  const acceptedRegion = new Map();
  for (const offer of offers) {
    const region = canonical(offer.company, offer.regionLabel);
    if (!region || !offer.candidate) continue;
    const key = String(offer.candidate);
    if (!offerRegion.has(key)) offerRegion.set(key, region);
    if (String(offer.status ?? "") === "accepted" && !acceptedRegion.has(key)) {
      acceptedRegion.set(key, region);
    }
  }

  const candidates = await db
    .collection("atscandidates")
    .find(
      { joiningRegionLabel: UNSET_REGION },
      { projection: { job: 1, company: 1, firstName: 1, lastName: 1 } },
    )
    .toArray();

  const bySource = { acceptedOffer: 0, offer: 0, job: 0 };
  const unresolved = [];

  for (const candidate of candidates) {
    const key = String(candidate._id);
    const region =
      acceptedRegion.get(key) ||
      offerRegion.get(key) ||
      (candidate.job ? jobRegion.get(String(candidate.job)) : undefined) ||
      "";

    if (!region) {
      unresolved.push(candidate);
      continue;
    }

    if (acceptedRegion.get(key)) bySource.acceptedOffer += 1;
    else if (offerRegion.get(key)) bySource.offer += 1;
    else bySource.job += 1;

    if (!DRY_RUN) {
      await db
        .collection("atscandidates")
        .updateOne(
          { _id: candidate._id },
          {
            $set: {
              joiningRegionLabel: region,
              // Marked as derived rather than transferred so the UI can tell a
              // backfilled region from one a person chose.
              joiningRegionAssignedAt: null,
              joiningRegionAssignedBy: null,
            },
          },
        );
    }
  }

  const total = candidates.length;
  const filled = bySource.acceptedOffer + bySource.offer + bySource.job;
  const mode = DRY_RUN ? " (dry run — nothing written)" : "";

  console.log(
    `Scanned ${total} candidate(s) with no joining region.${mode}\n` +
      `  filled from accepted offer : ${bySource.acceptedOffer}\n` +
      `  filled from any offer     : ${bySource.offer}\n` +
      `  filled from job region    : ${bySource.job}\n` +
      `  left unassigned           : ${unresolved.length}\n` +
      `Candidates left unassigned stay visible to every recruiter and can be sent ` +
      `to a region from the job page ("Send to Region").`,
  );

  if (unresolved.length > 0) {
    const sample = unresolved.slice(0, 10).map((c) => {
      const name = `${c.firstName ?? ""} ${c.lastName ?? ""}`.trim() || String(c._id);
      return `    ${name} (${c._id})`;
    });
    console.log(`\nSample of unassigned candidates:\n${sample.join("\n")}`);
  }

  await mongoose.disconnect();
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
